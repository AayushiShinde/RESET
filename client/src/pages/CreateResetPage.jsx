import React, { useState } from 'react';
import { BookOpen, Sparkles, Clock, ArrowRight, ShieldAlert, Cpu, CheckCircle } from 'lucide-react';
import { generateResetPlan } from '../api.js';

export function CreateResetPage({ onBeginReset }) {
  const [activity, setActivity] = useState('reading');
  const [reason, setReason] = useState('I used to read all the time, but now whenever I have free time I just scroll.');
  const [durationMinutes, setDurationMinutes] = useState(30);
  const [preference, setPreference] = useState('');
  
  const [loading, setLoading] = useState(false);
  const [generatedChallenge, setGeneratedChallenge] = useState(null);
  const [error, setError] = useState(null);

  const sampleReasons = [
    'I used to read all the time, but now whenever I have free time I just scroll.',
    'I keep waiting until I have a full free hour, so I end up never starting.',
    'My attention spans feels fragmented by endless notifications.',
    'I want to reconnect with the physical feeling of reading paper books.'
  ];

  const activities = [
    { id: 'reading', label: 'Reading', icon: '📖', active: true },
    { id: 'movement', label: 'Movement', icon: '🏃', active: false, note: 'Coming Soon' },
    { id: 'nature', label: 'Nature', icon: '🌿', active: false, note: 'Coming Soon' },
    { id: 'creating', label: 'Creating', icon: '🎨', active: false, note: 'Coming Soon' },
    { id: 'connecting', label: 'Connecting', icon: '🤝', active: false, note: 'Coming Soon' }
  ];

  const handleGenerate = async (e) => {
    e?.preventDefault();
    if (!reason.trim()) {
      setError('Please tell us why you stopped or what is getting in the way.');
      return;
    }

    setLoading(true);
    setError(null);

    try {
      const data = await generateResetPlan({
        activity,
        reason,
        durationMinutes,
        preference
      });
      setGeneratedChallenge(data.challenge);
    } catch (err) {
      setError(err.message || 'Could not connect to Gemma service.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="container-narrow animate-fade" style={{ padding: '3rem 1.5rem' }}>
      {!generatedChallenge ? (
        <div>
          <div style={{ textAlign: 'center', marginBottom: '2.5rem' }}>
            <span className="badge badge-forest" style={{ marginBottom: '0.75rem' }}>
              Step 1 of 2
            </span>
            <h1>Design Your Re:Set</h1>
            <p style={{ marginTop: '0.5rem' }}>
              A small, intentional offline invitation generated by open-weight AI.
            </p>
          </div>

          <form onSubmit={handleGenerate} className="card" style={{ background: '#ffffff' }}>
            {/* 1. What do you want to return to? */}
            <div className="form-group">
              <label className="form-label">
                What do you want to return to?
              </label>
              <div style={{ display: 'grid', gridTemplateColumns: 'repeat(auto-fit, minmax(110px, 1fr))', gap: '0.75rem' }}>
                {activities.map((act) => (
                  <button
                    key={act.id}
                    type="button"
                    disabled={!act.active}
                    onClick={() => act.active && setActivity(act.id)}
                    className={`chip-btn ${activity === act.id ? 'active' : ''}`}
                    style={{
                      opacity: act.active ? 1 : 0.6,
                      cursor: act.active ? 'pointer' : 'not-allowed',
                      padding: '0.85rem 0.5rem',
                      display: 'flex',
                      flexDirection: 'column',
                      alignItems: 'center',
                      gap: '0.25rem'
                    }}
                  >
                    <span style={{ fontSize: '1.4rem' }}>{act.icon}</span>
                    <span style={{ fontSize: '0.85rem' }}>{act.label}</span>
                    {act.note && (
                      <span style={{ fontSize: '0.65rem', color: 'var(--earth-600)', fontStyle: 'italic' }}>
                        {act.note}
                      </span>
                    )}
                  </button>
                ))}
              </div>
            </div>

            {/* 2. Why did you stop? */}
            <div className="form-group">
              <label className="form-label" htmlFor="reason-input">
                What gets in the way? Why did you stop?
              </label>
              <textarea
                id="reason-input"
                className="form-textarea"
                rows={3}
                value={reason}
                onChange={(e) => setReason(e.target.value)}
                placeholder="e.g. I used to read a lot, but now I spend my free time scrolling..."
              />
              <div style={{ marginTop: '0.6rem' }}>
                <span style={{ fontSize: '0.78rem', color: 'var(--text-soft)', display: 'block', marginBottom: '0.4rem' }}>
                  Or pick a common friction:
                </span>
                <div style={{ display: 'flex', flexWrap: 'wrap', gap: '0.4rem' }}>
                  {sampleReasons.map((sample, idx) => (
                    <button
                      key={idx}
                      type="button"
                      onClick={() => setReason(sample)}
                      style={{
                        background: 'var(--bg-subtle)',
                        border: '1px solid var(--earth-200)',
                        borderRadius: 'var(--radius-full)',
                        padding: '0.25rem 0.65rem',
                        fontSize: '0.75rem',
                        color: 'var(--forest-900)',
                        cursor: 'pointer',
                        textAlign: 'left'
                      }}
                    >
                      "{sample.slice(0, 42)}..."
                    </button>
                  ))}
                </div>
              </div>
            </div>

            {/* 3. Duration */}
            <div className="form-group">
              <label className="form-label">
                How much time do you have?
              </label>
              <div className="chip-grid">
                {[15, 30, 45, 60].map((mins) => (
                  <button
                    key={mins}
                    type="button"
                    onClick={() => setDurationMinutes(mins)}
                    className={`chip-btn ${durationMinutes === mins ? 'active' : ''}`}
                    style={{ display: 'flex', alignItems: 'center', justifyContent: 'center', gap: '0.4rem' }}
                  >
                    <Clock size={16} />
                    <span>{mins} minutes</span>
                  </button>
                ))}
              </div>
            </div>

            {error && (
              <div style={{
                background: '#fdf2f0',
                border: '1px solid #f2cfc7',
                borderRadius: 'var(--radius-md)',
                padding: '0.85rem 1rem',
                color: '#a33320',
                fontSize: '0.9rem',
                marginBottom: '1.25rem'
              }}>
                {error}
              </div>
            )}

            <button
              type="submit"
              disabled={loading}
              className="btn btn-primary"
              style={{ width: '100%', padding: '1rem', fontSize: '1.05rem' }}
              id="btn-generate-reset"
            >
              {loading ? (
                <>
                  <Sparkles size={18} className="animate-spin" />
                  Gemma is crafting your offline Re:Set...
                </>
              ) : (
                <>
                  <Cpu size={18} />
                  Generate Re:Set with Gemma AI
                  <ArrowRight size={18} />
                </>
              )}
            </button>
          </form>
        </div>
      ) : (
        /* CHALLENGE PREVIEW */
        <div>
          <div style={{ textAlign: 'center', marginBottom: '2rem' }}>
            <span className="badge badge-forest" style={{ marginBottom: '0.75rem' }}>
              Your Invitation is Ready
            </span>
            <h1>{generatedChallenge.title || 'Your first Re:Set'}</h1>
            <p>
              Generated specifically for you by {generatedChallenge._aiMetadata?.model || 'Gemma 2'}.
            </p>
          </div>

          <div className="card" style={{ background: '#ffffff', border: '2px solid var(--forest-800)', marginBottom: '2rem' }}>
            {/* Model Provenance Banner */}
            <div style={{
              display: 'flex',
              alignItems: 'center',
              justifyContent: 'space-between',
              paddingBottom: '1.25rem',
              marginBottom: '1.5rem',
              borderBottom: '1px solid var(--earth-200)',
              fontSize: '0.85rem',
              flexWrap: 'wrap',
              gap: '0.5rem'
            }}>
              <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
                <Cpu size={16} style={{ color: 'var(--forest-700)' }} />
                <span>Engine: <strong>{generatedChallenge._aiMetadata?.provider || 'Gemma 2'}</strong></span>
              </div>
              <span className={`badge ${generatedChallenge._aiMetadata?.isFallback ? 'badge-earth' : 'badge-forest'}`}>
                {generatedChallenge._aiMetadata?.isFallback ? 'Deterministic Fallback' : 'Open-Weight Verified'}
              </span>
            </div>

            <div style={{ display: 'flex', flexDirection: 'column', gap: '1.5rem' }}>
              {/* Duration & Activity */}
              <div style={{
                background: 'var(--forest-50)',
                padding: '1.25rem',
                borderRadius: 'var(--radius-md)',
                display: 'flex',
                alignItems: 'center',
                gap: '1rem'
              }}>
                <div style={{ fontSize: '2.2rem' }}>📖</div>
                <div>
                  <h3 style={{ fontSize: '1.35rem', color: 'var(--forest-900)' }}>
                    Read for {generatedChallenge.duration_minutes || durationMinutes} minutes
                  </h3>
                  <p style={{ fontSize: '0.9rem', color: 'var(--forest-700)' }}>
                    Single physical or paper book. No multiple open tabs.
                  </p>
                </div>
              </div>

              {/* Location Rule */}
              <div style={{ display: 'flex', alignItems: 'flex-start', gap: '0.9rem' }}>
                <div style={{ fontSize: '1.4rem' }}>📍</div>
                <div>
                  <h4 style={{ fontSize: '1rem', fontWeight: 600, color: 'var(--forest-900)' }}>Location</h4>
                  <p style={{ fontSize: '0.95rem' }}>{generatedChallenge.location_suggestion}</p>
                </div>
              </div>

              {/* Phone Rule */}
              <div style={{ display: 'flex', alignItems: 'flex-start', gap: '0.9rem' }}>
                <div style={{ fontSize: '1.4rem' }}>📵</div>
                <div>
                  <h4 style={{ fontSize: '1rem', fontWeight: 600, color: 'var(--forest-900)' }}>Phone Rule</h4>
                  <p style={{ fontSize: '0.95rem' }}>{generatedChallenge.phone_rule}</p>
                </div>
              </div>

              {/* Reflection Prompt */}
              <div style={{ display: 'flex', alignItems: 'flex-start', gap: '0.9rem' }}>
                <div style={{ fontSize: '1.4rem' }}>🌱</div>
                <div>
                  <h4 style={{ fontSize: '1rem', fontWeight: 600, color: 'var(--forest-900)' }}>Reflection Anchor</h4>
                  <p style={{ fontSize: '0.95rem' }}>{generatedChallenge.reflection_prompt}</p>
                </div>
              </div>
            </div>

            <div style={{
              marginTop: '2rem',
              paddingTop: '1.5rem',
              borderTop: '1px solid var(--earth-200)',
              display: 'flex',
              flexDirection: 'column',
              gap: '1rem'
            }}>
              <button
                onClick={() => onBeginReset(generatedChallenge)}
                className="btn btn-primary btn-large"
                id="btn-begin-reset"
                style={{ width: '100%', fontSize: '1.15rem' }}
              >
                Begin Re:Set
                <ArrowRight size={20} />
              </button>

              <button
                type="button"
                onClick={() => setGeneratedChallenge(null)}
                className="btn btn-quiet"
                style={{ alignSelf: 'center' }}
              >
                ← Adjust settings or generate another
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
